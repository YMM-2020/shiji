// Build stats from mock data
export function computeStats(memories: Memory[]): MemoryStats {
  const byType: Record<string, number> = {}
  let high = 0, medium = 0, low = 0
  let active = 0, dormant = 0, archived = 0

  memories.forEach((m) => {
    byType[m.type] = (byType[m.type] || 0) + 1
    if (m.confidence >= 0.8) high++
    else if (m.confidence >= 0.5) medium++
    else low++
    if (m.status === 'active') active++
    else if (m.status === 'dormant') dormant++
    else archived++
  })

  // Compute weekly new from actual creation dates
  const weeklyNew: { date: string; count: number }[] = []
  const now = new Date()
  for (let i = 4; i >= 0; i--) {
    const start = new Date(now)
    start.setDate(start.getDate() - (i * 7 + 6))
    const end = new Date(now)
    end.setDate(end.getDate() - i * 7)
    if (i === 0) end.setDate(end.getDate() + 1) // include today
    const count = memories.filter((m) => {
      const d = new Date(m.createdAt)
      return d >= start && d < end
    }).length
    const label = `${start.getMonth() + 1}/${start.getDate()}`
    weeklyNew.push({ date: label, count })
  }

  return {
    total: memories.length,
    byType: byType as MemoryStats['byType'],
    byConfidence: { high, medium, low },
    byStatus: { active, dormant, archived },
    pendingReview: memories.filter((m) => m.confidence < 0.7 && m.source === 'inferred').length,
    conflicts: 0,
    weeklyNew,
  }
}
